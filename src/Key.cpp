#include "Key.h"  // 引入评估密钥类的头文件

// ============================================================================
// 参数化构造函数
// 直接传入已有的多项式数组指针来构造评估密钥对象。
// 注意：此处为浅拷贝（shallow copy），即直接使用外部传入的指针，
//       不分配新内存。调用者需保证指针在密钥生命周期内有效。
// 参数：
//   ax - 评估密钥第一分量 a(X) 的多项式系数数组（NTT 域，RNS 存储）
//   bx - 评估密钥第二分量 b(X) 的多项式系数数组（NTT 域，RNS 存储）
// ============================================================================
Key::Key(uint64_t* ax, uint64_t* bx) : ax(ax), bx(bx) {}  // 初始化列表：直接绑定外部传入的 ax、bx 指针

// ============================================================================
// 虚析构函数
// 当前实现为空函数体。
// 因为 Key 类中 ax、bx 指向的外部内存由调用者管理（浅拷贝语义），
// 所以析构函数不释放这些内存。
// 声明为 virtual 是为了保证派生类（如重线性化密钥、旋转密钥等）
// 在被基类指针 delete 时能正确调用派生类的析构函数（多态析构）。
// ============================================================================
Key::~Key() {}  // 空析构函数：不释放 ax、bx（由外部管理者负责），仅作为虚函数占位以支持多态
